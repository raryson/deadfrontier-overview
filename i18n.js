export function resolveLanguage(preference = 'auto', languages = []) {
  if (preference === 'pt' || preference === 'en') return preference;
  for (const language of languages) {
    const base = String(language).toLowerCase().split(/[-_]/)[0];
    if (base === 'pt' || base === 'en') return base;
  }
  return 'en';
}
export const localeFor = language => language === 'pt' ? 'pt-BR' : 'en-US';
export function t(key, language = 'en', values = {}) {
  return (messages[language]?.[key] ?? messages.en[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
export function effectLabel(key, language = 'en') {
  const [base, ex] = key.split('_');
  return `${base === 'exp' ? 'EXP' : t(base, language)}${ex ? ' EX' : ''} +${base === 'exp' ? '50' : '35'}%`;
}
export function translateMessage(message, language) {
  if (language === 'pt' || typeof message !== 'string') return message;
  const key = Object.keys(messages.pt).find(key => messages.pt[key] === message);
  if (key) return t(key, language);
  return message
    .replace('Não foi possível confirmar a operação', 'Unable to confirm the operation')
    .replace('Não foi possível confirmar o saldo', 'Unable to confirm the balance')
    .replace('Confira o saldo no jogo antes de repetir.', 'Check your in-game balance before trying again.')
    .replace('resposta redirecionada para', 'response redirected to')
    .replace('outro domínio', 'another domain')
    .replace('resposta vazia', 'empty response')
    .replace('servidor retornou HTML', 'server returned HTML')
    .replace('bolso', 'cash').replace('banco', 'bank')
    .replaceAll('ausente', 'missing').replaceAll('inválido', 'invalid').replaceAll('presente', 'present')
    .replace('saldo fora do limite numérico', 'balance outside numeric limits')
    .replace('falha ao interpretar resposta', 'response parsing failed')
    .replace('erro de rede', 'network error')
    .replace('tempo de resposta esgotado', 'response timed out')
    .replace('requisição cancelada', 'request cancelled')
    .replace('falha ao enviar requisição', 'request could not be sent');
}
